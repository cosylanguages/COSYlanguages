nouns = {}

def add_noun(key, level, government, pattern, definition, grammar_rule, verb_key, linked_noun_keys, examples, common_mistake, synonyms, antonyms):
    assert key not in nouns, f"Duplicate key: {key}"

    related_forms = None
    if verb_key:
        assert verb_key in verbs_keys, f"Verb key '{verb_key}' not found in verbs.json!"
        related_forms = f"⚡ Ουσιαστικό: '{key}' ➜ Ρήμα: '{verb_key}'"

    assert len(examples) == 2, f"Examples must be an array of exactly 2 strings for {key}"

    nouns[key] = {
        "word_type": "noun",
        "government": government,
        "pattern": pattern,
        "level": level,
        "definition": definition,
        "grammar_rule": grammar_rule,
        "related_forms": related_forms,
        "linked_noun_keys": linked_noun_keys,
        "examples": examples,
        "common_mistake": common_mistake,
        "synonyms": synonyms,
        "antonyms": antonyms
    }

