# Helper to locate prev/next topic
all_flat_topics = []
for sec in SECTIONS:
    for top in sec["topics"]:
        all_flat_topics.append((sec, top))

def get_prev_next(slug):
    for idx, (sec, top) in enumerate(all_flat_topics):
        if top["slug"] == slug:
            prev_top = all_flat_topics[idx - 1][1] if idx > 0 else None
            next_top = all_flat_topics[idx + 1][1] if idx < len(all_flat_topics) - 1 else None
            return prev_top, next_top
    return None, None

