def translate_session(filename):
    src_file = os.path.join(SRC_DIR, filename)
    dest_file = os.path.join(DEST_DIR, filename)

    if not os.path.exists(src_file):
        print(f"❌ Source file not found: {src_file}")
        return

    meta = TRANSLATIONS.get(filename, {
        "title": "Не могла не задуматься...",
        "level": "Выше среднего (B2)",
        "theme": "Психология отношений и общество",
        "setting": "Ренн / Бретань",
        "metaphor": "Индивидуальность vs Социальные ожидания",
        "query": "О чем мы размышляем в тишине городской жизни?",
        "focus": "Развитие речи и критическое мышление",
        "date": "16 Марта 2027",
        "polaroid": "Ренн — '27",
        "prose": "Глядя на улицы города, я не могла не задуматься о скрытых силах, которые управляют нашей жизнью..."
    })

    with open(src_file, "r", encoding="utf-8") as f:
        content = f.read()

    soup = BeautifulSoup(content, "html.parser")

    # Update html lang
    if soup.html:
        soup.html["lang"] = "ru"

    # Update Title
    if soup.title:
        soup.title.string = f"{meta['title']} — COSYlanguages"

    # Update Hero H1
    h1 = soup.find("h1")
    if h1:
        h1.string = meta["title"]

    # Update Hero Date & Polaroid
    hero_date = soup.find("p", class_="session-date")
    if hero_date:
        hero_date.string = meta["date"]

    caption = soup.find("div", class_="polaroid-caption")
    if caption:
        caption.string = meta["polaroid"]

    # Update Breadcrumbs
    bc = soup.find("nav", class_="cosy-breadcrumbs")
    if bc:
        bc.clear()
        bc.append(BeautifulSoup(f'<a href="../../../../../../index.html">Главная</a><span class="sep"> / </span><a href="../../../../../../events/ru/index.html">События</a><span class="sep"> / </span><a href="../../i-couldnt-help-but-wonder.html">I Couldn\'t Help But Wonder</a><span class="sep"> / </span><span class="current">{meta["title"]}</span>', "html.parser"))

    # Back link
    back = soup.find("a", class_="back-link")
    if back:
        back.string = "← Назад в клуб"
        back["href"] = "../../i-couldnt-help-but-wonder.html"

    # Perspective Panel
    panel_meta = soup.find("div", class_="panel-meta-row")
    if panel_meta:
        panel_meta.clear()
        panel_meta.append(BeautifulSoup(f'<span>🌍 ЯЗЫК : <span style="color: var(--ink, #1F104D); font-weight: 600;">🇷🇺</span></span><span>📊 УРОВЕНЬ : <span style="color: var(--ink, #1F104D); font-weight: 600;">{meta["level"]}</span></span><span>🎯 ТЕМА : <span style="color: var(--ink, #1F104D); font-weight: 600;">{meta["theme"]}</span></span>', "html.parser"))

    grid_items = soup.find_all("div", class_="wonder-column-item")
    if len(grid_items) >= 4:
        grid_items[0].find("p").string = meta["setting"]
        grid_items[1].find("p").string = meta["metaphor"]
        grid_items[2].find("p").string = meta["query"]
        grid_items[3].find("p").string = meta["focus"]

    # Column Transcript
    transcript = soup.find("details", class_="transcript-details")
    if transcript:
        sum_span = transcript.find("summary")
        if sum_span:
            sum_span.clear()
            sum_span.append(BeautifulSoup('<span>📜 Читать текст колонки</span><span class="fold-arrow">▼</span>', "html.parser"))

        t_div = transcript.find("div")
        if t_div:
            t_div.clear()
            t_div.append(BeautifulSoup(f'<p>{meta["prose"]}</p><p style="margin-top: 1rem; font-size: 0.85rem; color: var(--muted); font-style: normal; font-weight: 500;">💌 Особая благодарность редакции COSY за разработку этой сессии.</p>', "html.parser"))

    # Footer
    footer = soup.find("footer")
    if footer:
        f_nav = footer.find("div", class_="footer-nav")
        if f_nav:
            f_nav.clear()
            f_nav.append(BeautifulSoup('<a href="../../../../../../index.html" style="color:var(--muted);text-decoration:none;">Главная</a><a href="../../../../../../practice/index.html" style="color:var(--muted);text-decoration:none;">Практика</a><a href="../../../../../../games/index.html" style="color:var(--muted);text-decoration:none;">Игры</a><a href="../../../../../../events/ru/index.html" style="color:var(--muted);text-decoration:none;">События</a>', "html.parser"))
        copy_p = footer.find("p")
        if copy_p:
            copy_p.string = "© 2026 COSYlanguages — Все права защищены"

    # Write out converted Russian session
    with open(dest_file, "w", encoding="utf-8") as f:
        f.write(str(soup))

    print(f"✅ Generated Russian session: {filename}")

def main():
    os.makedirs(DEST_DIR, exist_ok=True)
    for filename in sorted(os.listdir(SRC_DIR)):
        if filename.endswith(".html"):
            translate_session(filename)

if __name__ == "__main__":
    main()
